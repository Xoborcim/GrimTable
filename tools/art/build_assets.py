def collection(name):
    obj = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(obj)
    return obj


def link_only(obj, group):
    for old in list(obj.users_collection):
        old.objects.unlink(obj)
    group.objects.link(obj)


def atlas():
    """Shared deterministic pigment texture and rough/metal atlas; no downloads."""
    directory = ROOT / "assets/miniatures/materials"
    directory.mkdir(parents=True, exist_ok=True)
    rng = random.Random(120)
    size = 1024
    pixels = [0.0] * (size * size * 4)
    orm = [0.0] * (size * size * 4)
    for y in range(size):
        for x in range(size):
            tile = x // 256 + (y // 256) * 4
            _, color, metal, rough = PALETTE[tile]
            rgb = [int(color[i:i+2], 16) / 255 for i in [0, 2, 4]]
            u, v = (x % 256) / 255, (y % 256) / 255
            brush = .98 + .009 * sin(u*17 + sin(v*9)) + .007*rng.random()
            # Uneven painterly pigment. Fine scratches stay sparse and restrained.
            chip = rng.random() > .9975
            for c in range(3):
                value = rgb[c] * brush * (1.12 if chip else 1)
                # Generated byte-image pixels are written directly to the sRGB
                # PNG. Do not pre-degamma here (that darkens the glTF twice).
                pixels[(y*size+x)*4+c] = value
            pixels[(y*size+x)*4+3] = 1
            orm[(y*size+x)*4:(y*size+x)*4+4] = [1, min(1,rough+.025*rng.random()), metal, 1]
    images=[]
    for name, data, space in [("painted_atlas",pixels,"sRGB"),("painted_orm",orm,"Non-Color")]:
        image=bpy.data.images.new(name,width=size,height=size,alpha=False)
        image.colorspace_settings.name=space
        image.pixels.foreach_set(data)
        image.filepath_raw=str(directory/(name+".png"))
        image.file_format="PNG"
        image.save()
        images.append(image)
    mat=bpy.data.materials.new("GT_0120_PaintedAtlas")
    mat.use_nodes=True
    nodes=mat.node_tree.nodes
    bsdf=nodes.get("Principled BSDF")
    base=nodes.new("ShaderNodeTexImage"); base.image=images[0]
    masks=nodes.new("ShaderNodeTexImage"); masks.image=images[1]
    channels=nodes.new("ShaderNodeSeparateColor")
    mat.node_tree.links.new(base.outputs["Color"],bsdf.inputs["Base Color"])
    mat.node_tree.links.new(masks.outputs["Color"],channels.inputs["Color"])
    mat.node_tree.links.new(channels.outputs["Green"],bsdf.inputs["Roughness"])
    mat.node_tree.links.new(channels.outputs["Blue"],bsdf.inputs["Metallic"])
    return mat


