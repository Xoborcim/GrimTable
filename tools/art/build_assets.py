def clean_game_mesh(data):
    # Boolean/bevel intersections can leave microscopic zero-area polygons.
    # Remove only those polygons, retaining all real geometry and split normals.
    data.update()
    bad=[poly.index for poly in data.polygons if poly.area<=1e-14]
    if not bad: return
    if len(bad)>max(30,len(data.polygons)//100):
        raise ValueError('Unexpected degenerate topology: '+str(len(bad)))
    normals=[tuple(normal.vector) for normal in data.corner_normals]
    keep=[normals[loop] for poly in data.polygons if poly.index not in set(bad) for loop in poly.loop_indices]
    bm=bmesh.new(); bm.from_mesh(data); bm.faces.ensure_lookup_table()
    bmesh.ops.delete(bm,geom=[bm.faces[index] for index in bad],context='FACES_ONLY')
    bm.to_mesh(data); bm.free(); data.update()
    if len(keep)==len(data.loops): data.normals_split_custom_set(keep)
    print('GAME MESH CLEANUP',len(bad),'zero-area polygons removed')


