        evaluated=obj.evaluated_get(deps)
        data=bpy.data.meshes.new_from_object(evaluated,depsgraph=deps)
        new=bpy.data.objects.new(obj.name+"__game",data)
        new.matrix_world=obj.matrix_world.copy()
