def mesh(name, verts, faces, tile=0, edge=1, bevel=.20, smooth=False):
    data=bpy.data.meshes.new(name+"_topology")
    data.from_pydata([tuple(v*MM for v in point) for point in verts],[],faces)
    data.update()
    bm=bmesh.new(); bm.from_mesh(data)
    bmesh.ops.recalc_face_normals(bm,faces=list(bm.faces))
    bm.to_mesh(data); bm.free()
    obj=bpy.data.objects.new(name,data); SOURCE.objects.link(obj)
    data.materials.append(MATS[tile]); data.materials.append(MATS[edge])
    for face in data.polygons: face.use_smooth=smooth
    if bevel:
        modifier=obj.modifiers.new("Machined edge / painted highlight","BEVEL")
        modifier.width=bevel*MM; modifier.segments=2
        modifier.limit_method="ANGLE"; modifier.angle_limit=.38
        modifier.material=1
        modifier.harden_normals=True
        normal=obj.modifiers.new("Area weighted plate normals","WEIGHTED_NORMAL")
        normal.keep_sharp=True; normal.weight=40
    return obj


def loft(name, rings, tile=0, edge=1, bevel=.2, sides=12, smooth=False, power=3.0):
    """A purpose-shaped extrusion with variable cross sections, not a scaled cube."""
    verts=[]
    for z,x,y,width,depth in rings:
        for i in range(sides):
            a=2*pi*i/sides
            cx=math.copysign(abs(cos(a))**(2/power),cos(a))
            cy=math.copysign(abs(sin(a))**(2/power),sin(a))
            verts.append((x+cx*width/2,y+cy*depth/2,z))
    faces=[]
    for ring in range(len(rings)-1):
        for i in range(sides):
            j=(i+1)%sides
            faces.append((ring*sides+i,ring*sides+j,(ring+1)*sides+j,(ring+1)*sides+i))
    faces.extend([tuple(reversed(range(sides))),tuple((len(rings)-1)*sides+i for i in range(sides))])
    return mesh(name,verts,faces,tile,edge,bevel,smooth)


def panel(name, outline, y, depth, tile=0, edge=1, bevel=.22, crown=.0):
    """Extruded armor silhouette, with an inset perimeter and convex front surface."""
    n=len(outline)
    cx=sum(x for x,z in outline)/n; cz=sum(z for x,z in outline)/n
    verts=[(x,y+depth,z) for x,z in outline]+[(x,y,z) for x,z in outline]
    verts += [(cx+(x-cx)*.86,y-crown,cz+(z-cz)*.86) for x,z in outline]
    faces=[tuple(reversed(range(n))),tuple(2*n+i for i in range(n))]
    for i in range(n):
        j=(i+1)%n
        faces.extend([(i,j,n+j,n+i),(n+i,n+j,2*n+j,2*n+i)])
    return mesh(name,verts,faces,tile,edge,bevel)


def extrude_outline(name, outline, y, depth, tile=12, edge=13, bevel=.5):
    # Concave architectural contours need a true planar cap, not an armor inset.
    clean=[]
    for point in outline:
        if not clean or (Vector(point)-Vector(clean[-1])).length>.001: clean.append(point)
    if (Vector(clean[0])-Vector(clean[-1])).length<.001: clean.pop()
    n=len(clean)
    vertices=[(x,y,z) for x,z in clean]+[(x,y+depth,z) for x,z in clean]
    faces=[tuple(range(n)),tuple(reversed([n+i for i in range(n)]))]
    faces.extend((i,(i+1)%n,(i+1)%n+n,i+n) for i in range(n))
    return mesh(name,vertices,faces,tile,edge,bevel)


def position(obj, point):
    obj.location=Vector(point)*MM
    return obj


def span(name, start, end, widths, tile=3, edge=14, sides=12):
    length=(Vector(end)-Vector(start)).length
    rings=[(t*length,0,0,w,d) for t,w,d in widths]
    obj=loft(name,rings,tile,edge,.10,sides,power=2.6)
    obj.rotation_mode="QUATERNION"
    obj.rotation_quaternion=(Vector(end)-Vector(start)).to_track_quat('Z','Y')
    position(obj,start)
    return obj


def tube(name, points, radius=.35, tile=3, resolution=8):
    curve=bpy.data.curves.new(name+"_sweep","CURVE"); curve.dimensions="3D"
    curve.resolution_u=resolution; curve.bevel_depth=radius*MM; curve.bevel_resolution=2
    spline=curve.splines.new("BEZIER"); spline.bezier_points.add(len(points)-1)
    for point, value in zip(spline.bezier_points,points):
        point.co=Vector(value)*MM
        point.handle_left_type="AUTO"; point.handle_right_type="AUTO"
    obj=bpy.data.objects.new(name,curve); SOURCE.objects.link(obj)
    curve.materials.append(MATS[tile]); return obj


def annulus(name, center, radius, width, thickness, tile=3, axis='Y', segments=20):
    verts=[]
    for axial,r in [(-thickness/2,radius),(-thickness/2,radius-width),(thickness/2,radius-width),(thickness/2,radius)]:
        for i in range(segments):
            a=i*2*pi/segments
            point=(r*cos(a),axial,r*sin(a)) if axis=='Y' else (axial,r*cos(a),r*sin(a)) if axis=='X' else (r*cos(a),r*sin(a),axial)
            verts.append(tuple(Vector(center)+Vector(point)))
    faces=[]
    for row in range(4):
        for i in range(segments):
            j=(i+1)%segments; nxt=(row+1)%4
            faces.append((row*segments+i,row*segments+j,nxt*segments+j,nxt*segments+i))
    return mesh(name,verts,faces,tile,14,.08)


def bolt(name, at, size=.38, tile=5, axis='Y'):
    obj=loft(name,[(-.15,0,0,size*2,size*2),(.15,0,0,size*2,size*2)],tile,tile,.04,6,power=2)
    if axis=='Y': obj.rotation_euler[0]=pi/2
    elif axis=='X': obj.rotation_euler[1]=pi/2
    position(obj,at); return obj


def boolean_cut(target, cutter):
    bpy.context.view_layer.objects.active=target
    modifier=target.modifiers.new("Recess machined into shell","BOOLEAN")
    modifier.operation='DIFFERENCE'; modifier.solver='EXACT'; modifier.object=cutter
    # Boolean comes before bevels so the cut edges receive a proper highlight.
    bpy.ops.object.modifier_move_to_index(modifier=modifier.name,index=0)
    bpy.ops.object.modifier_apply(modifier=modifier.name)
    if not target.data.polygons: raise ValueError('Boolean removed the entire shell: '+target.name)
    bpy.data.objects.remove(cutter,do_unlink=True)


def ribbed_joint(name, start, end, radius, rings=5):
    span(name+" / flexible core",start,end,[(0,radius*1.7,radius*1.7),(1,radius*1.7,radius*1.7)],4,3)
    direction=Vector(end)-Vector(start)
    for i in range(rings):
        at=Vector(start)+direction*((i+.5)/rings)
        obj=annulus(name+" / seal %02d"%i,(0,0,0),radius,.18,.30,3,axis='Z',segments=12)
        obj.rotation_mode='QUATERNION'; obj.rotation_quaternion=direction.to_track_quat('Z','Y'); position(obj,at)


def cloth(name, top, bottom, width, tile=7):
    verts=[]; nx,ny=8,9
    for j in range(ny):
        t=j/(ny-1)
        for i in range(nx):
            u=i/(nx-1)-.5
            z=top*(1-t)+bottom*t + (sin(i*2.4)*.45 if j==ny-1 else 0)
            verts.append((u*width*(1-.12*t),-4.5-.8*t+sin(u*11+t*1.5)*(.3+t*.6),z))
    faces=[]
    for j in range(ny-1):
        for i in range(nx-1):
            a=j*nx+i; faces.append((a,a+1,a+1+nx,a+nx))
    obj=mesh(name,verts,faces,tile,tile,0,True)
    solid=obj.modifiers.new("Actual fabric thickness","SOLIDIFY"); solid.thickness=.18*MM
    sub=obj.modifiers.new("Fold interpolation","SUBSURF"); sub.levels=1; sub.render_levels=1
    return obj


