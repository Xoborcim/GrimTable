        # Molded jamb: sloped inset, base, shaft and capital are distinct profiles.
        loft(name+" / %s jamb"%side,[(sill,x,y+5,8,13),(sill+3,x,y+5,9.5,14),(spring-3,x,y+5,7,12),(spring,x,y+5,9,14)],12,2,.55,sides=12)
        curve=arch_curve(cx,spring,width,rise,side)
        for i in range(len(curve)-1):
            if broken and side>0 and i>7: continue
            a,b=Vector(curve[i]),Vector(curve[i+1])
            tangent=(b-a).normalized()
            normal=Vector((-tangent.y,tangent.x))*side
            if normal.y<0: normal=-normal
